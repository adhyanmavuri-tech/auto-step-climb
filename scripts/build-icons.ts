// Draws the app's icons: build/icon.png and build/icon.ico for the installer, and the tray icons as a TypeScript
// file the app carries inside itself (electron/icons.generated.ts), so there are no image files to find at run time.
//
//   npm run build-icons
//
// The results are checked in. This only needs running when the drawing in electron/icon-art.ts changes.
import fs from 'node:fs'
import path from 'node:path'
import { appIcon, DOT_COLORS, encodeIco, encodePng, trayIcon } from '../electron/icon-art.ts'
import type { TrayLevel } from '../electron/icon-art.ts'

const root = path.resolve(import.meta.dirname, '..')
const png = (size: number, pixels: Uint8Array): Buffer => encodePng(size, size, pixels)

// The installer and the app's window: a 512 picture, and an icon file with the sizes Windows asks for.
fs.mkdirSync(path.join(root, 'build'), { recursive: true })
fs.writeFileSync(path.join(root, 'build', 'icon.png'), png(512, appIcon(512)))
const sizes = [16, 24, 32, 48, 64, 128, 256]
fs.writeFileSync(path.join(root, 'build', 'icon.ico'), encodeIco(sizes.map((size) => ({ size, png: png(size, appIcon(size)) }))))

// The tray: Windows picks the picture for the screen's scale (100%, 150%, 200%, 300%).
const scales: [number, number][] = [
  [1, 16],
  [1.5, 24],
  [2, 32],
  [3, 48]
]
const levels = Object.keys(DOT_COLORS) as TrayLevel[]
const lines = [
  '// Generated by scripts/build-icons.ts from electron/icon-art.ts. Do not edit by hand.',
  '',
  "export type TrayLevel = 'ok' | 'busy' | 'attention' | 'problem' | 'off'",
  '',
  '/** The tray icon for each status: a picture for each screen scale, as base64 PNG. */',
  'export const TRAY_ICONS: Record<TrayLevel, { scale: number; png: string }[]> = {'
]
for (const level of levels) {
  lines.push(`  ${level}: [`)
  for (const [scale, size] of scales) lines.push(`    { scale: ${scale}, png: '${png(size, trayIcon(size, DOT_COLORS[level])).toString('base64')}' },`)
  lines.push('  ],')
}
lines.push('}', '', '/** The app icon, 256 pixels, as base64 PNG: the window and the notifications use it. */')
lines.push(`export const APP_ICON_PNG = '${png(256, appIcon(256)).toString('base64')}'`, '')
fs.writeFileSync(path.join(root, 'electron', 'icons.generated.ts'), lines.join('\n'))

console.log('Wrote build/icon.png, build/icon.ico and electron/icons.generated.ts')
for (const f of ['build/icon.png', 'build/icon.ico', 'electron/icons.generated.ts']) console.log(`  ${f}: ${(fs.statSync(path.join(root, f)).size / 1024).toFixed(1)} KB`)
